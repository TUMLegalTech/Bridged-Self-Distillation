#!/usr/bin/env python3
"""Generate the hint and guide forms of the privileged context from the traces of a BSD parquet.

Forms (the BSD-hint and BSD-guide variants):
  guide  numbered step-by-step guide: at most eight steps of the solution in order, no computation, no intermediate
         numbers, no final answer
  hint   at most three sentences naming the key idea, no final answer (the HINT_INSTRUCTION of
         generate_trace_hints.py)
The final answer is appended later, by build_pi_form_views.py --append-answer.
The text is generated by the teacher model through the OpenRouter chat-completions API (OPENROUTER_API_KEY from the
environment, never written anywhere). Per row: one candidate first; when it contains the ground-truth answer string
(`answer_leaks`), up to --max-candidates further samples are drawn and the first clean one is kept; if every candidate
leaks, the shortest is kept and the row is flagged. The output is resumable JSONL, one row per uid:
  {uid, form, text, answer_leak, n_candidates, prompt_tokens, completion_tokens, model}
Run with the training interpreter (pandas, openai client). The trace's <think> tags are removed before prompting.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_trace_hints import HINT_INSTRUCTION, answer_leaks  # noqa: E402

GUIDE_INSTRUCTION = """You are helping a student who is stuck on a math problem. Below are the problem and a worked reasoning trace written by a stronger solver.

Problem:
{problem}

Worked reasoning:
{trace}

Write a step-by-step guide for the student: a numbered list of the steps of the solution, in order, at most 8 steps and under 150 words in total. Rules: each step says what to do and why (the idea, the quantity to set up, the case split), without carrying out the computation; do not state the final answer; do not give intermediate numerical results; do not restate the problem; plain text, no markdown formatting. Output only the numbered list."""

FORMS = {
    "guide": (GUIDE_INSTRUCTION, 700),
    "hint": (HINT_INSTRUCTION, 300),
}
THINK_TAGS = re.compile(r"</?think>")
LIST_MARKERS = re.compile(r"(?m)^\s*\d+[.)]\s*")
NO_THINK = " /no_think"  # Qwen3 soft switch; the API flag below is not honoured by every OpenRouter provider


def strip_think_tags(trace: str) -> str:
    return THINK_TAGS.sub("", trace).strip()


def leaks(text: str, ground_truth: str) -> bool:
    """answer_leaks on the text without its numbered-list labels ("6." of step 6 is not the answer 6)."""
    return answer_leaks(LIST_MARKERS.sub("", text), ground_truth)


def strip_reasoning(text: str) -> str:
    """Some providers return the reasoning block inline; keep only what follows it."""
    if "</think>" in text:
        text = text.split("</think>", 1)[1]
    return text.strip()


def load_rows(parquet: str, trace_field: str) -> list[dict]:
    import pandas as pd

    df = pd.read_parquet(parquet)
    rows = []
    for e, rm in zip(df["extra_info"], df["reward_model"]):
        rows.append({"uid": str(e["uid"]), "problem": str(e["problem"]), "trace": strip_think_tags(str(e[trace_field])),
                     "ground_truth": str(rm["ground_truth"])})
    return rows


def generate_row(call, row: dict, form: str, max_candidates: int) -> dict:
    """call(prompt, max_tokens) -> (text, finish_reason, prompt_tokens, completion_tokens).

    One candidate first; another only when the candidate leaks the answer or was cut at max_tokens."""
    instruction, max_tokens = FORMS[form]
    prompt = instruction.format(problem=row["problem"], trace=row["trace"]) + NO_THINK
    cands, p_tok, c_tok, n_calls, truncated = [], 0, 0, 0, 0
    for _ in range(max_candidates):
        text, finish, pt, ct = call(prompt, max_tokens)
        n_calls += 1; p_tok += pt; c_tok += ct
        text = strip_reasoning(text)
        if finish == "length" or not text:
            truncated += finish == "length"
            continue
        cands.append(text)
        if not leaks(text, row["ground_truth"]):
            break
    clean = [c for c in cands if not leaks(c, row["ground_truth"])]
    text = clean[0] if clean else (min(cands, key=len) if cands else "")
    return {"uid": row["uid"], "form": form, "text": text, "answer_leak": not clean, "n_candidates": n_calls,
            "truncated_candidates": truncated, "prompt_tokens": p_tok, "completion_tokens": c_tok}


def openrouter_call(client, model: str, temperature: float, top_p: float):
    def call(prompt: str, max_tokens: int):
        for attempt in range(4):
            try:
                r = client.chat.completions.create(
                    model=model, messages=[{"role": "user", "content": prompt}], temperature=temperature, top_p=top_p,
                    max_tokens=max_tokens,  # thinking is off through the /no_think switch; the kwarg helps where honoured
                    extra_body={"chat_template_kwargs": {"enable_thinking": False}, "provider": {"sort": "throughput"}})
                text = r.choices[0].message.content or ""
                u = r.usage
                return text, r.choices[0].finish_reason, (u.prompt_tokens if u else 0), (u.completion_tokens if u else 0)
            except Exception as exc:  # rate limits and transient provider errors
                if attempt == 3:
                    raise
                time.sleep(5 * (attempt + 1))
                last = exc
        raise last
    return call


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--parquet", required=True)
    p.add_argument("--form", required=True, choices=sorted(FORMS))
    p.add_argument("--out", required=True)
    p.add_argument("--trace-field", default="qwen32b_pi_trace")
    p.add_argument("--model", default="qwen/qwen3-32b")
    p.add_argument("--max-candidates", type=int, default=4)
    p.add_argument("--concurrency", type=int, default=16)
    p.add_argument("--temperature", type=float, default=0.7)
    p.add_argument("--top-p", type=float, default=0.95)
    p.add_argument("--limit", type=int, default=0, help="only the first N rows (smoke test)")
    args = p.parse_args()

    from openai import OpenAI

    key = os.environ.get("OPENROUTER_API_KEY")
    if not key:
        raise SystemExit("OPENROUTER_API_KEY is not set")
    client = OpenAI(base_url="https://openrouter.ai/api/v1", api_key=key)
    call = openrouter_call(client, args.model, args.temperature, args.top_p)

    rows = load_rows(args.parquet, args.trace_field)
    if args.limit:
        rows = rows[: args.limit]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    done = set()
    if out.exists():
        done = {json.loads(line)["uid"] for line in out.read_text().splitlines() if line.strip()}
    todo = [r for r in rows if r["uid"] not in done]
    print(f"{args.form}: {len(rows)} rows, {len(done)} already done, {len(todo)} to generate with {args.model}", flush=True)
    lock = threading.Lock()
    stats = {"rows": 0, "leak": 0, "cands": 0, "trunc": 0, "p": 0, "c": 0}
    with out.open("a") as f, ThreadPoolExecutor(args.concurrency) as pool:
        for rec in pool.map(lambda r: generate_row(call, r, args.form, args.max_candidates), todo):
            rec["model"] = args.model
            with lock:
                f.write(json.dumps(rec) + "\n"); f.flush()
                stats["rows"] += 1; stats["leak"] += rec["answer_leak"]; stats["cands"] += rec["n_candidates"]
                stats["trunc"] += rec["truncated_candidates"]; stats["p"] += rec["prompt_tokens"]; stats["c"] += rec["completion_tokens"]
                if stats["rows"] % 100 == 0:
                    print(f"  {stats['rows']}/{len(todo)} rows, leak rows {stats['leak']}, candidates {stats['cands']}, "
                          f"truncated {stats['trunc']}, tokens in {stats['p']/1e6:.2f}M out {stats['c']/1e6:.3f}M", flush=True)
    print(json.dumps({"form": args.form, "generated": stats["rows"], "all_candidates_leak": stats["leak"],
                      "candidates": stats["cands"], "truncated_candidates": stats["trunc"],
                      "prompt_tokens": stats["p"], "completion_tokens": stats["c"]}))


if __name__ == "__main__":
    main()
